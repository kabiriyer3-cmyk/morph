export const STRINGS = { en, ru: { ...en, ...ru } };

let lang = 'en';
export const getLang = () => lang;

export function setLang(l) {
  lang = STRINGS[l] ? l : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export function detectLang() {
  try {
    const s = JSON.parse(localStorage.getItem('morph.settings') || '{}');
    if (s && s.lang && STRINGS[s.lang]) return s.lang;
  } catch {
    // ignore broken settings
  }
  const n = (typeof navigator !== 'undefined' && navigator.language) || '';
  return n.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

export function t(key, vars) {
  let s = STRINGS[lang][key];
  if (s == null) s = STRINGS.en[key];
  if (s == null) s = key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
  return s;
}

const tr = (key) => (lang === 'en' ? undefined : STRINGS[lang][key]);

export function nodeTitle(type) {
  const d = NODE_DEFS[type];
  return tr('node.' + type) || (d ? d.title : type);
}

export function nodeDesc(type) {
  const d = NODE_DEFS[type];
  return tr('desc.' + type) || (d ? d.desc : '');
}

export function wLabel(w) {
  return tr('w.' + w.name) || w.label || w.name.split('_').join(' ');
}

export function optLabel(w, o) {
  const base = (w.labels && w.labels[o]) || String(o);
  return tr('o.' + base) || base;
}

export const sockLabel = (name) => tr('s.' + name) || name;
export const catLabel = (cat) => t('cat.' + cat);

export function tplText(tpl, what) {
  if (what === 'desc') return tr('tpl.' + tpl.id + '.d') || tpl.desc;
  return tr('tpl.' + tpl.id) || tpl.title;
}

export function applyI18n(root) {
  root.querySelectorAll('[data-i18n]').forEach((e) => {
    e.textContent = t(e.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((e) => {
    e.title = t(e.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((e) => {
    e.placeholder = t(e.dataset.i18nPlaceholder);
  });
}
